#!/usr/bin/env python3
"""Bundle the report datasets into a single web/data.js (window.MCPDATA).
Re-run after the scan finishes so scan numbers are real.
"""
import json, os, datetime

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DATA = os.path.join(ROOT, "data")
WEB = os.path.join(ROOT, "web")
os.makedirs(WEB, exist_ok=True)

def load(fn):
    p = os.path.join(DATA, fn)
    if os.path.exists(p):
        return json.load(open(p))
    return None

servers = (load("servers.json") or {})
skills = (load("skills.json") or {})
eco = (load("ecosystem.json") or {})
scan = load("scan.json") or load("scan_results.json")

if scan and "results" in scan:
    scan_block = scan
else:
    scan_block = {"status": "pending",
                  "totals": {"repos": len(eco.get("scanned_repos", [])), "files_scanned": None,
                             "findings_total": None, "verdicts": {"PASS": 0, "REVIEW": 0, "FAIL": 0}},
                  "results": []}

def slim(r):
    return {k: r.get(k) for k in ("full_name", "name", "owner", "stars", "forks", "desc",
                                   "lang", "pushed", "created", "category", "scanned",
                                   "verdict", "files_scanned", "findings_total", "homepage",
                                   "open_issues") if k in r}

for r in servers.get("servers", []):
    r.setdefault("verdict", None)
for r in skills.get("skills", []):
    r.setdefault("verdict", None)

# Normalize scan-result repo names to full "owner/repo" so they match
# ecosystem.scanned_repos and the server/skill row full_name values.
# The scanner keys results by the cloned dir (short name); short name == full_name.split('/')[1].
scanned_full = eco.get("scanned_repos", []) or []
short2full = {fn.split("/")[-1]: fn for fn in scanned_full if "/" in fn}
for res in scan_block.get("results", []):
    res["repo"] = short2full.get(res.get("repo"), res.get("repo"))

# attach scan verdicts to server + skill rows (matched by full_name)
vmap = {res["repo"]: res for res in scan_block.get("results", [])}
if vmap:
    for r in list(servers.get("servers", [])) + list(skills.get("skills", [])):
        res = vmap.get(r.get("full_name"))
        if res:
            r["verdict"] = res["verdict"]
            r["files_scanned"] = res["files_scanned"]
            r["findings_total"] = res["findings_total"]

payload = {
    "meta": {
        "title": "The State of MCP Servers",
        "as_of": servers.get("as_of") or "2026-11-10",
        "generated": datetime.datetime.utcnow().strftime("%Y-%m-%dT%H:%M:%SZ"),
        "brand": "Gardu",
        "scanner": "Gardu static scanner (Hexbane rule philosophy, HB101-HB701)",
        "version": "v1.0",
        "scan_status": scan_block.get("status", "done" if vmap else "pending"),
    },
    "ecosystem": eco,
    "servers": servers,
    "skills": skills,
    "scan": scan_block,
}
js = "/* generated by scan/make_webdata.py - do not edit by hand */\nwindow.MCPDATA = " + json.dumps(payload, ensure_ascii=False, indent=1) + ";\n"
with open(os.path.join(WEB, "data.js"), "w", encoding="utf-8") as f:
    f.write(js)
print("wrote web/data.js", len(js), "bytes; servers", len(servers.get("servers", [])),
      "skills", len(skills.get("skills", [])), "scan_status", payload["meta"]["scan_status"],
      "verdicts", scan_block["totals"].get("verdicts"))
